#!/bin/python

import io

import kisstype as kiss

print(f"kisstype bindings {kiss.__version__}, library version {kiss.getVersion()}")

# Build a spectra by hand.
data = [
	kiss.DataPoint(complex(10, -2), 1000),
	kiss.DataPoint(complex(20, -8), 100),
	kiss.DataPoint(complex(30, -12), 10),
]
spectra = kiss.Spectra(data, "r{1e1}c{1e-6}", "example spectra")
spectra.headerDescription = "generated by example.py"
spectra.addLabel("temperature", 298.15)

print(f"{len(spectra)} data points, first one: {spectra[0]}")
print(f"temperature label: {spectra.getLabel('temperature')}")
print(f"abs of the first point: {abs(spectra[0])}")

real, imag = kiss.eisToValarrays(spectra.data)
print(f"real: {real}")
print(f"imag: {imag}")

# Round trip through a file and through a stream.
spectra.saveToDisk("/tmp/example.eis")
loaded = kiss.Spectra.loadFromDisk("/tmp/example.eis")
print(f"loaded {len(loaded)} points again, model: {loaded.model}")

buffer = io.StringIO()
spectra.saveToStream(buffer)
buffer.seek(0)
print(f"loaded from stream: {len(kiss.Spectra.loadFromStream(buffer))} points")

# Ranges, for example to generate the frequencies to measure at.
omega = kiss.Range(1, 1e5, 5, True)
print(f"range: {omega.getString(True)}, sane: {omega.isSane()}")
print(f"elements: {[f'{v:.1f}' for v in omega]}")
print(f"parsed back: {kiss.Range.fromString('1~100000L:5', 1)}")
